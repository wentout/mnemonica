export const call = function <E extends object, T extends object, Args extends unknown[]>(
	entity: E,
	Ctor: CtorParameter<T, Args>,
	...args: NoInfer<Args>
): InstanceResult<Merge<E, T>> {
	const runResult = $run<E, T, Args>(
		entity,
		Ctor,
		args
	);
	// same merge narrowing as apply() above
	const result = runResult as InstanceResult<Merge<E, T>>;
	return result;
};

// TODO: bind type .with instance → (...args)
export const bind = function <E extends object, T extends object, Args extends unknown[]>(
	entity: E,
	Ctor: CtorParameter<T, Args>
): (...args: Args) => InstanceResult<Merge<E, T>> {
	const result = (...args: Args) => {
		const runResult = $run<E, T, Args>(
			entity,
			Ctor,
			args
		);
		// same merge narrowing as apply() above
		const typedResult = runResult as InstanceResult<Merge<E, T>>;
		return typedResult;
	};
	return result;
};

export const decorate = function <
	T extends Constructor<object> | constructorOptions | undefined = undefined
>(
	target?: T,
	config?: constructorOptions
): <U extends Constructor<object>>(cstr: U) => DecoratedClass<U> {
	const opts = (config === undefined && typeof target === 'object' && !(target instanceof Function))
		? target as constructorOptions
		: config;

	// decorate(SomeType, config?) expects a constructor already carrying
	// .define (a previously defined type) — declared on the value so the
	// decorator body below needs no cast
	const parentType = (target instanceof Function)
		? target as Constructor<object> & { define: TypeAbsorber }
		: undefined;

	// decorator contract: define() returns the constructor that wraps cstr;
	// the decorator replaces the class binding with it, so callers see the
	// result as DecoratedClass<U>. The overload states that contract; the
	// implementation signature (not emitted) returns what define() gives.
	function decorator <U extends Constructor<object>>(cstr: U): DecoratedClass<U>;
	function decorator (cstr: Constructor<object>): object {
		const { name } = cstr;
		const handler: IDEF<object, never[]> = cstr;
		if (parentType === undefined) {
			const decoratorResult = define(
				name,
				handler,
				opts
			);
			return decoratorResult;
		}
		// same decorator contract as the branch above
		const defineResult = parentType.define(
			name,
			handler,
			opts
		);
		return defineResult;
	}
	return decorator;
};


